// Builds src/data/samai.ts from datasets/ga-samai*.jsonl (the archive's samai records).
// One entry per symbol; each source's reading is kept separately, with its dataset,
// so the site only shows readings whose dataset has been imported.
//   node scripts/build-samai.mjs
import fs from "node:fs";
const files = { "ga-samai.jsonl": "datasets/ga-samai.jsonl", "ga-samai-okaikoi.jsonl": "datasets/ga-samai-okaikoi.jsonl" };
const fold = (s) => s.normalize("NFD").replace(/\p{M}/gu, "").toLowerCase().replace(/ɛ/g, "e").replace(/ɔ/g, "o").replace(/ŋ/g, "n");
// Spellings that name the same symbol in different sources.
const SAME = { "abii woo nii ahe nu": "abii woo ni ahe nu", "atswaa": "atswa" };
const LOCAL_IMG = { "abii woo ni ahe nu": "abii-woo-ni-ahe-nu", abui: "abui", akpakpa: "akpakpa", asamankama: "asamankama", asrafoi: "asrafoi", atoobi: "atoobi", atswa: "atswa", hinmeisee: "hinmeisee" };
const symbols = new Map();
for (const [dataset, path] of Object.entries(files)) {
  for (const line of fs.readFileSync(path, "utf8").split("\n").filter(Boolean)) {
    const r = JSON.parse(line);
    if (!r.image) continue; // the overview record, not a symbol
    let key = fold(r.ga); key = SAME[key] || key;
    const slug = key.replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
    // Keep the wording; only a trailing "— a samai symbol" tag adds nothing on a samai page.
    const meaning = r.english.trim().replace(/\s*—\s*a samai symbol$/, "").replace(/^./, (ch) => ch.toUpperCase());
    let image = r.image;
    if (dataset === "ga-samai.jsonl" && LOCAL_IMG[key]) image = `/img/samai/${LOCAL_IMG[key]}.png`;
    else image = image.replace(/^https:\/\/app\.speakga\.org/, "");
    if (!symbols.has(slug)) symbols.set(slug, { slug, name: r.ga, readings: [] });
    symbols.get(slug).readings.push({
      dataset, name: r.ga, meaning, image,
      source: r.source, source_url: r.source_url || (dataset === "ga-samai.jsonl" ? "https://www.adinkrasymbols.org/pages/ga-samai/" : null),
      note: r.note || null, image_credit: r.image_credit || null,
    });
  }
}
const out = `// Generated by scripts/build-samai.mjs from datasets/ga-samai*.jsonl. Do not edit by hand.
export interface SamaiReading { dataset: string; name: string; meaning: string; image: string; source: string; source_url: string | null; note: string | null; image_credit: string | null }
export interface SamaiSymbol { slug: string; name: string; readings: SamaiReading[] }
export const SAMAI: SamaiSymbol[] = ${JSON.stringify([...symbols.values()].sort((a, b) => a.slug.localeCompare(b.slug)), null, 2)};
`;
fs.writeFileSync("src/data/samai.ts", out);
