// Builds src/data/archive.ts from the imported datasets: the Ga words and phrases each
// dataset holds (as matching keys), and the stories and poems in the Library. The
// Worker unions these keys with the vocabulary table to count distinct words and phrases.
//   node scripts/build-archive.mjs
// foldKey must stay identical to foldKey in src/rag/archive-stats.ts.
import fs from "node:fs";

const foldKey = (s) => String(s || "").normalize("NFD").replace(/\p{M}/gu, "").toLowerCase()
  .replace(/ɛ/g, "e").replace(/ɔ/g, "o").replace(/ŋ/g, "n").replace(/[^a-z0-9 ]/g, "").replace(/\s+/g, " ").trim();
const load = (f) => fs.readFileSync(`datasets/${f}.jsonl`, "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l));

// Datasets of Ga words and phrases with English (phonetics is about sounds, not words).
const WORD_SETS = [
  "ga-language-guide", "ga-language-guide-full", "ga-language-guide-phrases", "ga-language-guide-extra",
  "ga-language-guide-supplement", "ga-months-culture", "ga-polytranslator", "ga-wikivoyage-phrasebook",
  "ga-ucla-conversation-1980", "ga-bible-books",
];
const keys = new Set();
for (const f of WORD_SETS) for (const r of load(f)) {
  const k = foldKey(r.ga);
  if (r.english && k && k.length <= 120) keys.add(k);
}

// Stories: one per storybook, titled by its title record.
const storyRows = [...load("ga-storybooks-ghana"), ...load("ga-storybooks-asb")];
const stories = [...new Set(storyRows.map((r) => r.story))].map((id) => {
  const rows = storyRows.filter((r) => r.story === id);
  const title = rows.find((r) => /title/.test(r.topic || ""))?.english || rows[0].english;
  return { id, title, lines: rows.length, source: rows[0].source };
});
// Poems and songs: each named piece with at least a few lines (single quoted lines are excerpts).
const poemRows = load("ga-poetry").filter((r) => r.poem);
const poems = [...new Set(poemRows.map((r) => r.poem))]
  .map((slug) => {
    const rows = poemRows.filter((r) => r.poem === slug);
    const title = (rows.find((r) => r.title && !/\(.*full.*\)/.test(r.title))?.title || rows[0].title || slug).replace(/\s*\(full\)$/, "");
    return { slug, title, lines: rows.length, genre: rows[0].genre || "" };
  })
  .filter((p) => p.lines >= 3);

const out = `// Generated by scripts/build-archive.mjs from rag-cloudflare/datasets. Do not edit by hand.
export const DATASET_WORD_KEYS: string[] = ${JSON.stringify([...keys].sort())};
export const STORIES = ${JSON.stringify(stories, null, 2)};
export const POEMS = ${JSON.stringify(poems, null, 2)};
`;
fs.writeFileSync("src/data/archive.ts", out);
console.log(`${keys.size} word/phrase keys · ${stories.length} stories (${stories.map((s) => s.title).join(", ")}) · ${poems.length} poems and songs (${poems.map((p) => p.title).join(", ")})`);
