const fold = (s) => s.toLowerCase().replace(/\s+/g, " ").trim();
const existing = new Set();
const existingEnglish = new Map(); // english -> ga
for (const f of readdirSync("datasets")) {
  if (!f.endsWith(".jsonl")) continue;
  for (const line of readFileSync(join("datasets", f), "utf8").split("\n")) {
    if (!line.trim()) continue;
    try {
      const r = JSON.parse(line);
      if (r.english) {
        existing.add(fold(r.english) + "|" + fold(r.ga || ""));
        existingEnglish.set(fold(r.english), r.ga);
      }
    } catch {}
  }
}
// also datasets-negab not needed (bible only)

const seen = new Set();
const out = [];
let skipped = 0, conflicts = 0;
for (const [english, ga, topic, page] of R) {
  const key = fold(english);
  if (existing.has(key + "|" + fold(ga)) || seen.has(key)) { skipped++; continue; }
  seen.add(key);
  const rec = { english, ga, topic, source: SRC, page };
  const prev = existingEnglish.get(key);
  if (prev && fold(prev) !== fold(ga)) {
    rec.note = `variant vs existing record "${prev}"`;
    conflicts++;
  }
  out.push(rec);
}

writeFileSync(
  "datasets/ga-language-guide-extra.jsonl",
  out.map((r) => JSON.stringify(r)).join("\n") + "\n"
);
const topics = {};
for (const r of out) topics[r.topic] = (topics[r.topic] || 0) + 1;
